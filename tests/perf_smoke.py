#!/usr/bin/env python3
"""Performance check: boot the ISO in a 4 GB VM, let the desktop settle, measure it at idle.

Measures with `nullgrid perf` (memory as PSS per component, CPU over a minute) in the Hyprland
desktop and in the Sway (lite) one, plus the boot timeline (systemd-analyze, when each part of
the desktop came up). Writes out/perf/report.md + report.json and checks the targets:
memory used at the idle desktop < 700 MiB for the lite (Sway) session and < 750 MiB for the
Hyprland one (software rendering inflates Hyprland and kitty; see docs/PERFORMANCE.md), the
shell (all widgets), wallpaper and sound daemon each < 2% of a core.

The VM has no 3D (Mesa draws in software), which makes the CPU numbers pessimistic.

Usage: perf_smoke.py [--settle SECONDS] [--window SECONDS]   (normally via `make perf`)
"""
import argparse
import json
import os
import subprocess
import sys
import tempfile
import time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import boot_smoke as bs  # noqa: E402

OUT = os.path.join(bs.ROOT, "out", "perf")
MEM_LIMIT = {"Hyprland desktop": 750 * 1024**2, "Sway desktop (lite)": 700 * 1024**2}
CPU_LIMIT = 2.0            # percent of one core, per component
LIMITED = ("shell", "wallpaper", "sound")


def mib(n: int) -> str:
    return f"{n / 1024**2:.0f} MiB"


def measure(c: bs.Checker, label: str, window: int) -> dict | None:
    out = c.con.run(f"sudo nullgrid perf --seconds {window} --top 15 --json | tr -d '\\n'", window + 120)
    try:
        data = json.loads("".join(out))
    except ValueError:
        c.verify(f"{label}: nullgrid perf output", False, " | ".join(out)[-300:])
        return None
    print(f"[info] {label}: memory used {mib(data['mem_used'])}, CPU {data['cpu_total']}% of the machine")
    for name, u in sorted(data["components"].items(), key=lambda kv: -kv[1]["mem"]):
        print(f"[info]   {name:<18}{mib(u['mem']):>9}{u['cpu']:>7.2f}%  up at {u['started']}s")
    return data


def check(c: bs.Checker, label: str, data: dict) -> None:
    limit = MEM_LIMIT[label]
    c.verify(f"{label}: memory used < {mib(limit)}", data["mem_used"] < limit, mib(data["mem_used"]))
    for name in LIMITED:
        u = data["components"].get(name)
        if u is not None:
            c.verify(f"{label}: {name} CPU < {CPU_LIMIT}%", u["cpu"] < CPU_LIMIT, f"{u['cpu']}%")


def report_md(results: dict, boot: list[str], blame: list[str], boot_seconds: float) -> str:
    lines = ["# NULLGRID performance report", "",
             f"Live ISO in QEMU/KVM, 4 GB RAM, 2 CPUs, virtio-gpu without 3D (software rendering). "
             f"Generated by `make perf` on {time.strftime('%Y-%m-%d')}.", "",
             f"Power-on to shell prompt (serial): {boot_seconds:.0f} s", "", "```", *boot, "```", "",
             "Slowest units:", "", "```", *blame, "```", ""]
    for label, data in results.items():
        lines += [f"## {label}", "",
                  f"Memory used (MemTotal - MemAvailable): **{mib(data['mem_used'])}**; "
                  f"CPU over {data['seconds']:g} s: {data['cpu_total']}% of the machine.", "",
                  "| component | memory (PSS) | CPU (% of a core) | processes | up at (s after boot) |",
                  "|---|---:|---:|---:|---:|"]
        for name, u in sorted(data["components"].items(), key=lambda kv: -kv[1]["mem"]):
            lines.append(f"| {name} | {mib(u['mem'])} | {u['cpu']:.2f} | {u['procs']} | {u['started']} |")
        lines += ["", "| process | memory (PSS) | CPU | component |", "|---|---:|---:|---|"]
        for t in data["top"]:
            lines.append(f"| {t['name']} | {mib(t['mem'])} | {t['cpu']:.2f} | {t['component']} |")
        lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--settle", type=int, default=90, help="seconds to let the desktop settle")
    ap.add_argument("--window", type=int, default=60, help="seconds to measure CPU over")
    args = ap.parse_args()

    tmp = tempfile.mkdtemp()
    mon_path = os.path.join(tmp, "monitor.sock")
    t0 = time.monotonic()
    con = bs.Console([os.path.join(bs.ROOT, "build", "run-vm.sh"), "--serial", f"--monitor={mon_path}"])
    c = bs.Checker(con)
    results: dict = {}
    try:
        con.wait_for(bs.PROMPT, bs.BOOT_TIMEOUT)
        boot_seconds = time.monotonic() - t0
        con.send("exec bash --norc --noprofile --noediting")
        time.sleep(2)
        con.run("stty -echo; PS1=''; export TERM=dumb SYSTEMD_COLORS=0", 30)
        mon = bs.Monitor(mon_path)

        # Hyprland: the default desktop
        c.wait("pgrep -x quickshell >/dev/null && pgrep -x swaybg >/dev/null && echo UP", "UP", 180)
        boot = con.run("systemd-analyze; systemd-analyze critical-chain multi-user.target --no-pager | tail -n 12", 60)
        blame = con.run("systemd-analyze blame --no-pager | head -n 12", 60)
        print(f"[info] settling {args.settle}s")
        time.sleep(args.settle)
        mon.screenshot("perf-hyprland")
        if (d := measure(c, "Hyprland desktop", args.window)) is not None:
            results["Hyprland desktop"] = d

        # Sway: the lite profile
        con.run(f"{bs.ENV}; hyprctl dispatch exit >/dev/null; sleep 3", 60)
        con.run("sed -i 's/^profile = \"full\"/profile = \"lite\"/' ~/.config/nullgrid/nullgrid.toml"
                " && nullgrid theme reload >/dev/null", 120)
        bs.restart_tty1(c)
        if c.wait("pgrep -x sway >/dev/null && pgrep -x quickshell >/dev/null && echo UP", "UP", 180):
            time.sleep(args.settle)
            mon.screenshot("perf-sway")
            if (d := measure(c, "Sway desktop (lite)", args.window)) is not None:
                results["Sway desktop (lite)"] = d

        for label, data in results.items():
            check(c, label, data)
        os.makedirs(OUT, exist_ok=True)
        with open(os.path.join(OUT, "report.json"), "w") as fh:
            json.dump({"boot_seconds": boot_seconds, "boot": boot, "blame": blame, "results": results}, fh, indent=2)
        with open(os.path.join(OUT, "report.md"), "w") as fh:
            fh.write(report_md(results, boot, blame, boot_seconds))
        uid, gid = os.environ.get("HOST_UID"), os.environ.get("HOST_GID")
        if uid and gid:
            for p in (OUT, os.path.join(OUT, "report.json"), os.path.join(OUT, "report.md")):
                os.chown(p, int(uid), int(gid))
        print(f"[info] report: {os.path.relpath(os.path.join(OUT, 'report.md'), bs.ROOT)}")
        con.send("sudo poweroff")
        con.vm.wait(timeout=120)
    except (TimeoutError, RuntimeError, OSError, subprocess.TimeoutExpired) as exc:
        print(f"[FAIL] {exc}")
        print(con.text[-3000:])
        c.failures.append(str(exc))
    finally:
        if con.vm.poll() is None:
            con.vm.kill()
    print("PASS" if not c.failures else f"FAIL ({len(c.failures)} problem(s))")
    return 1 if c.failures else 0


if __name__ == "__main__":
    sys.exit(main())
